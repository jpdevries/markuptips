#!/usr/bin/env node
// Sync the canonical rules (rules/*.md, an OKF v0.2 bundle) into the site.
//   node scripts/sync-rules.mjs          # write pages/rules/*.mdx and lib/rules.ts
//   node scripts/sync-rules.mjs --check  # exit 1 if anything is out of date
// - pages/rules/<slug>.mdx is a byte-for-byte copy of rules/<slug>.md (Rex compiles the
//   YAML frontmatter into `export const frontmatter` and drops it from the rendered body).
// - lib/rules.ts is generated from each rule's frontmatter (title, description, icon),
//   in the order the bullets appear in rules/index.md.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const rulesDir = join(root, 'rules');
const pagesDir = join(root, 'pages', 'rules');
const check = process.argv.includes('--check');
const RESERVED = new Set(['index.md', 'log.md', 'README.md']);

const parse = (raw) => {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  return m ? YAML.parse(m[1]) ?? {} : null;
};

const units = new Map();
for (const name of readdirSync(rulesDir)) {
  if (!name.endsWith('.md') || RESERVED.has(name)) continue;
  const slug = name.slice(0, -3);
  const raw = readFileSync(join(rulesDir, name), 'utf8');
  const fm = parse(raw);
  if (!fm) fail(`rules/${name}: no frontmatter block`);
  if (fm.type !== 'Rule') fail(`rules/${name}: expected type: Rule, got ${fm.type}`);
  for (const k of ['title', 'description', 'icon']) if (!fm[k]) fail(`rules/${name}: frontmatter needs \`${k}\``);
  units.set(slug, { raw, fm });
}

// Order comes from the hand-written root index.
const index = readFileSync(join(rulesDir, 'index.md'), 'utf8');
const order = [...index.matchAll(/^\* \[[^\]]+\]\(([^)]+)\.md\)/gm)].map((m) => m[1]).filter((s) => !RESERVED.has(`${s}.md`));
for (const slug of units.keys()) if (!order.includes(slug)) fail(`rules/index.md does not list ${slug}.md`);
for (const slug of order) if (!units.has(slug)) fail(`rules/index.md lists ${slug}.md, which does not exist`);

const icons = [...new Set(order.map((s) => units.get(s).fm.icon))].sort();
const str = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const rulesTs = `// Generated by scripts/sync-rules.mjs from rules/*.md frontmatter and rules/index.md.
// Do not edit by hand: edit the rule's frontmatter, then run \`npm run sync:rules\`.
import {
${icons.map((i) => `  ${i},`).join('\n')}
} from '@phosphor-icons/react';

export const RULES = [
${order.map((slug) => { const { title, description, icon } = units.get(slug).fm; return `  { slug: ${str(slug)}, title: ${str(title)}, summary: ${str(description)}, Icon: ${icon} },`; }).join('\n')}
];
`;

let stale = 0;
const sync = (path, want) => {
  const have = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (have === want) return;
  stale++;
  if (check) console.log(`out of date: ${path.slice(root.length + 1)}`);
  else { writeFileSync(path, want); console.log(`wrote ${path.slice(root.length + 1)}`); }
};
for (const [slug, { raw }] of units) sync(join(pagesDir, `${slug}.mdx`), raw);
for (const name of readdirSync(pagesDir)) {
  if (name.endsWith('.mdx') && !units.has(name.slice(0, -4))) fail(`pages/rules/${name} has no rules/${name.slice(0, -4)}.md`);
}
sync(join(root, 'lib', 'rules.ts'), rulesTs);

if (check && stale) fail(`${stale} file(s) out of date; run \`npm run sync:rules\``);
console.log(check ? `in sync: ${units.size} rules` : `synced ${units.size} rules`);

function fail(msg) { console.error(`sync-rules: ${msg}`); process.exit(1); }
